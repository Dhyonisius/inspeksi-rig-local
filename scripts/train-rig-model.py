"""Train a new rig hazard detector from an approved YOLO export, locally.

Run with data/private/detector-export-env/Scripts/python.exe. Training is
explicit and does not change Gemma or replace the installed SH17 detector.
"""
import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import zipfile
import threading
import time

ROOT = Path(__file__).resolve().parent.parent
os.environ.setdefault('YOLO_AUTOINSTALL', 'False')
os.environ['YOLO_OFFLINE'] = 'true'
os.environ.setdefault('YOLO_CONFIG_DIR', str(ROOT / 'data/private/rig-training/settings'))

EVENTS = False

def event(stage, **values):
    if EVENTS:
        print('RIG_EVENT ' + json.dumps({'stage': stage, **values}, ensure_ascii=False, allow_nan=False), flush=True)

def monitor_parent(pid):
    """Stop training when the launching server exits, including an abrupt exit."""
    if not pid:
        return
    if os.name == 'nt':
        import ctypes
        from ctypes import wintypes
        kernel = ctypes.WinDLL('kernel32', use_last_error=True)
        kernel.OpenProcess.argtypes = [wintypes.DWORD, wintypes.BOOL, wintypes.DWORD]
        kernel.OpenProcess.restype = wintypes.HANDLE
        kernel.WaitForSingleObject.argtypes = [wintypes.HANDLE, wintypes.DWORD]
        kernel.CloseHandle.argtypes = [wintypes.HANDLE]
        handle = kernel.OpenProcess(0x00100000, False, pid)
        if not handle:
            os._exit(130)
        kernel.WaitForSingleObject(handle, 0xFFFFFFFF)
        kernel.CloseHandle(handle)
        os._exit(130)
    while True:
        try:
            os.kill(pid, 0)
        except ProcessLookupError:
            os._exit(130)
        time.sleep(5)

def checksum(path):
    h=hashlib.sha256()
    with path.open('rb') as f:
        for chunk in iter(lambda:f.read(1024*1024),b''): h.update(chunk)
    return h.hexdigest()

def prepare_export(archive, destination):
    with zipfile.ZipFile(archive) as z:
        if len(z.infolist())>20000 or sum(i.file_size for i in z.infolist())>2*1024**3:
            raise ValueError('Paket terlalu besar untuk pelatihan lokal.')
        for info in z.infolist():
            name=PurePosixPath(info.filename)
            if name.is_absolute() or '..' in name.parts or '\\' in info.filename or ':' in info.filename:
                raise ValueError('Lokasi berkas dalam ZIP tidak valid.')
            if ((info.external_attr>>16)&0o170000)==0o120000:
                raise ValueError('ZIP tidak boleh memuat symbolic link.')
        z.extractall(destination)
    manifest=json.loads((destination/'manifest.json').read_text(encoding='utf8'))
    if manifest.get('dataset',{}).get('status')!='APPROVED': raise ValueError('Ekspor harus berasal dari dataset yang disetujui.')
    if manifest.get('format')!='yolo': raise ValueError('Gunakan ekspor YOLO dari aplikasi.')
    # Export layouts are generated by dataset-tools.js; no arbitrary config runs.
    train=list((destination/'images/train').glob('*'))
    validation=list((destination/'images/validation').glob('*'))
    test=list((destination/'images/test').glob('*'))
    if not train or not validation or not test:
        raise ValueError('Dataset harus memiliki TRAIN, VALIDATION, dan TEST dari kelompok berbeda.')
    group_splits={}
    seen_photos = set()
    session_splits = {}
    for item in manifest.get('items',[]):
        if item.get('label_status')!='VERIFIED' or not item.get('license_verified'):
            raise ValueError('Semua foto harus terverifikasi dan berizin.')
        relative=PurePosixPath(item.get('archive_image',''))
        if len(relative.parts) != 3 or relative.parts[0]!='images' or relative.parts[1] != str(item.get('split', '')).lower() or relative.parts[1] not in {'train', 'validation', 'test'} or relative.is_absolute() or '..' in relative.parts:
            raise ValueError('Asal foto tidak valid.')
        photo=destination/relative
        if checksum(photo)!=item.get('checksum'):raise ValueError('Checksum foto tidak sesuai.')
        if str(relative) in seen_photos:
            raise ValueError('Foto tercatat lebih dari sekali dalam paket.')
        seen_photos.add(str(relative))
        group=item.get('source_group_key') or item.get('source_live_session_id') or item.get('checksum')
        if group in group_splits and group_splits[group]!=item.get('split'):
            raise ValueError('Satu kelompok foto tidak boleh masuk beberapa pembagian.')
        group_splits[group]=item.get('split')
        for session in item.get('session_ids', []):
            if session in session_splits and session_splits[session] != item.get('split'):
                raise ValueError('Satu sesi foto berada dalam beberapa pembagian.')
            session_splits[session] = item.get('split')
    if not manifest.get('items'):raise ValueError('Paket tidak berisi contoh.')
    actual_photos = {p.relative_to(destination).as_posix() for p in (destination/'images').rglob('*') if p.is_file()}
    if actual_photos != seen_photos:
        raise ValueError('Daftar foto dan manifest tidak sesuai.')
    for split in ('TRAIN', 'VALIDATION', 'TEST'):
        if not any(i.get('split') == split and i.get('overall_label') == 'RISK' and i.get('annotations') for i in manifest['items']):
            raise ValueError('TRAIN, VALIDATION, dan TEST harus mempunyai contoh bahaya berkotak.')
    return manifest

def main():
    global EVENTS
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('export_zip',type=Path)
    parser.add_argument('--epochs',type=int,default=20)
    parser.add_argument('--image-size',type=int,default=640)
    parser.add_argument('--run-dir', type=Path)
    parser.add_argument('--json-events', action='store_true')
    parser.add_argument('--parent-pid', type=int)
    args=parser.parse_args()
    EVENTS = args.json_events
    if not 1<=args.epochs<=200 or args.image_size != 640:
        parser.error('Epoch 1–200; model yang dapat dipakai aplikasi menggunakan ukuran 640.')
    if args.parent_pid:
        threading.Thread(target=monitor_parent, args=(args.parent_pid,), daemon=True).start()
    archive=args.export_zip.resolve(strict=True)
    weight=ROOT/'models/sh17-yolov8n/source-yolo8n.pt'
    if not weight.is_file(): raise ValueError('Bobot awal lokal SH17 belum tersedia.')
    stamp=datetime.now(timezone.utc).strftime('%Y%m%d-%H%M%S')
    run = args.run_dir.resolve() if args.run_dir else ROOT/'data/private/rig-training'/stamp
    training_root = (ROOT/'data/private/rig-training').resolve()
    if run.parent != training_root:
        raise ValueError('Folder hasil harus berada dalam folder pelatihan proyek.')
    run.mkdir(parents=True,exist_ok=bool(args.run_dir))
    event('VALIDATING', message='Memeriksa snapshot foto dan label.')
    manifest=prepare_export(archive,run/'dataset')
    # Training uses installed libraries, local weights, and local fonts only.
    # Disable optional online integrations before importing the training library.
    import shutil
    settings_dir = Path(os.environ['YOLO_CONFIG_DIR'])
    settings_dir.mkdir(parents=True, exist_ok=True)
    font = Path(os.environ.get('WINDIR', 'C:/Windows'))/'Fonts/arial.ttf'
    if font.is_file():
        for filename in ('Arial.ttf', 'Arial.Unicode.ttf'):
            if not (settings_dir/filename).exists():
                shutil.copyfile(font, settings_dir/filename)
    import yaml
    from ultralytics import YOLO, settings
    settings.update({key: False for key in ('sync', 'wandb', 'clearml', 'comet', 'hub', 'dvc', 'mlflow', 'neptune', 'raytune', 'tensorboard') if key in settings})
    config=run/'dataset/dataset.yaml'
    if not config.exists(): config=run/'dataset/data.yaml'
    data=yaml.safe_load(config.read_text(encoding='utf8'))
    names=data.get('names')
    if not isinstance(names,(dict,list)) or not names: raise ValueError('Kelas detektor tidak tersedia.')
    if isinstance(names, dict):
        names = [names[index] for index in range(len(names))]
    if len(names) > 100 or any(not isinstance(name, str) or not name or len(name) > 160 for name in names):
        raise ValueError('Nama kelas detektor tidak valid.')
    if [row.get('name') for row in manifest.get('class_map', [])] != names:
        raise ValueError('Kelas YAML dan manifest tidak sesuai.')
    for item in manifest['items']:
        photo = run/'dataset'/item['archive_image']
        label = run/'dataset'/str(PurePosixPath(item['archive_image'])).replace('images/', 'labels/', 1)
        label = label.with_suffix('.txt')
        expected = item.get('annotations', [])
        lines = label.read_text(encoding='utf8').splitlines()
        if len(lines) != len(expected):
            raise ValueError('Kotak foto dan manifest tidak sesuai.')
        for line, box in zip(lines, expected):
            values = line.split()
            if len(values) != 5 or not values[0].isdigit() or not 0 <= int(values[0]) < len(names):
                raise ValueError('Kelas kotak tidak valid.')
            class_row = manifest['class_map'][int(values[0])]
            coords = [float(value) for value in values[1:]]
            target = [box['x'] + box['width']/2, box['y'] + box['height']/2, box['width'], box['height']]
            if class_row['hazard_type_id'] != box['hazard_type_id'] or any(not abs(a-b) <= 0.000001 for a,b in zip(coords,target)):
                raise ValueError('Label kotak tidak cocok dengan snapshot terverifikasi.')
    # Override paths from the archive; train/val/test are always confined here.
    config.write_text(yaml.safe_dump({'path':str((run/'dataset').resolve()),'train':'images/train','val':'images/validation','test':'images/test','names':names},sort_keys=False),encoding='utf8')
    model=YOLO(str(weight))
    import torch
    torch.set_num_threads(2)
    model.add_callback('on_train_epoch_end', lambda trainer: event('TRAINING', epoch=trainer.epoch+1, epochs=args.epochs, message='Epoch selesai.'))
    event('TRAINING', epoch=0, epochs=args.epochs, message='Melatih bobot detektor rig pada CPU.')
    model.train(data=str(config),epochs=args.epochs,imgsz=args.image_size,batch=2,device='cpu',
        workers=0,project=str(run),name='train',exist_ok=False,plots=False,seed=42,deterministic=True,patience=0)
    best=run/'train/weights/best.pt'
    trained=YOLO(str(best))
    event('EVALUATING', message='Mengukur kotak deteksi pada foto TEST terpisah.')
    measured=trained.val(data=str(config),split='test',device='cpu',plots=False)
    per_class = [{'class_id': int(index), 'name': names[int(index)], 'precision': float(measured.box.p[position]),
                  'recall': float(measured.box.r[position]), 'map50': float(measured.box.ap50[position])}
                 for position, index in enumerate(measured.box.ap_class_index)]
    test_items = [item for item in manifest['items'] if item['split'] == 'TEST']
    safety = {'test_photos': len(test_items), 'risk_photos': 0, 'risk_photos_without_detection': 0,
              'normal_photos': 0, 'normal_photos_with_detection': 0, 'confidence_threshold': 0.35}
    event('EVALUATING_PHOTOS', completed=0, total=len(test_items), message='Mengukur bahaya terlewat dan alarm keliru pada TEST.')
    for index, item in enumerate(test_items):
        prediction = trained.predict(source=str(run/'dataset'/item['archive_image']), imgsz=640, conf=0.35, iou=0.5, max_det=20, device='cpu', verbose=False)[0]
        found = prediction.boxes is not None and len(prediction.boxes) > 0
        if item['overall_label'] == 'RISK':
            safety['risk_photos'] += 1
            safety['risk_photos_without_detection'] += int(not found)
        elif item['overall_label'] == 'NO_LISTED_HAZARD_VISIBLE':
            safety['normal_photos'] += 1
            safety['normal_photos_with_detection'] += int(found)
        event('EVALUATING_PHOTOS', completed=index+1, total=len(test_items))
    event('EXPORTING', message='Mengekspor model ONNX untuk pemeriksaan lokal.')
    onnx=trained.export(format='onnx',imgsz=args.image_size,device='cpu',simplify=False)
    runtime = run/'runtime'
    runtime.mkdir(exist_ok=False)
    shutil.copyfile(onnx, runtime/'model.onnx')
    runtime_manifest = {'schema_version': 1, 'architecture': 'yolov8_raw', 'scope': 'rig_hazards', 'input_size': 640,
                        'model_file': 'model.onnx', 'model_name': 'Rig YOLO '+run.name, 'class_names': names,
                        'class_map': manifest['class_map'], 'sha256': checksum(runtime/'model.onnx')}
    (runtime/'manifest.json').write_text(json.dumps(runtime_manifest, ensure_ascii=False, indent=2), encoding='utf8')
    record={'version':'rig-'+stamp,'engine':'YOLO_ONNX','status':'CANDIDATE',
        'dataset_snapshot':manifest.get('snapshot_sha256'),'export_sha256':checksum(archive),
        'base_weight_sha256':checksum(weight),'weights_sha256':checksum(best),
        'weights_path':str(best),'onnx_path':str(onnx),'metrics':measured.results_dict,
        'classes':names,'class_map':manifest['class_map'],'per_class_metrics':per_class,'photo_metrics':safety,
        'dataset_id':manifest['dataset']['dataset_id'],'epochs':args.epochs,'image_size':args.image_size,
        'runtime_sha256':runtime_manifest['sha256'],
        'notes':'Model kandidat untuk kategori berlabel. Tidak ada deteksi bukan bukti aman. Gemma dan detektor SH17 tetap.'}
    (run/'model-version.json').write_text(json.dumps(record,ensure_ascii=False,indent=2),encoding='utf8')
    print('Pelatihan selesai. Versi kandidat:',run/'model-version.json')
    event('COMPLETED', message='Kandidat model dan metrik tersedia untuk ditinjau.')

if __name__=='__main__':main()
